CREATE TABLE makers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    shop_name VARCHAR(120) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maker_id BIGINT NOT NULL REFERENCES makers(id) ON DELETE CASCADE,
    sku VARCHAR(64) NOT NULL,
    title VARCHAR(200) NOT NULL,
    image_url VARCHAR(500),
    unit_cost NUMERIC(12,2) NOT NULL CHECK (unit_cost >= 0),
    retail_price NUMERIC(12,2) NOT NULL CHECK (retail_price >= 0),
    stock INTEGER NOT NULL CHECK (stock >= 0),
    low_stock_threshold INTEGER NOT NULL DEFAULT 5 CHECK (low_stock_threshold >= 0),
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_products_maker_sku UNIQUE (maker_id, sku)
);
CREATE INDEX idx_products_maker ON products(maker_id);

CREATE TABLE channels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maker_id BIGINT NOT NULL REFERENCES makers(id) ON DELETE CASCADE,
    name VARCHAR(80) NOT NULL,
    CONSTRAINT uq_channels_maker_name UNIQUE (maker_id, name)
);

-- Sales keep a cost snapshot so later COGS edits never rewrite history.
CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maker_id BIGINT NOT NULL REFERENCES makers(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id),
    channel_id BIGINT NOT NULL REFERENCES channels(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    unit_cost NUMERIC(12,2) NOT NULL CHECK (unit_cost >= 0),
    sold_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_sales_maker_date ON sales(maker_id, sold_at);
